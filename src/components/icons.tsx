/** Renders full, half and empty stars for ratings like 4.5. */
export function Stars({ rating, className = "h-4 w-4" }: { rating: number; className?: string }) {
  return (
    <div className="flex items-center gap-0.5" aria-label={`${rating} out of 5 stars`} role="img">
      {[1, 2, 3, 4, 5].map((i) => {
        const fill = rating >= i ? 1 : rating >= i - 0.5 ? 0.5 : 0;
        const id = `half-${i}-${rating}`;
        return (
          <svg key={i} viewBox="0 0 24 24" className={className} aria-hidden="true">
            <defs>
              <linearGradient id={id}>
                <stop offset={`${fill * 100}%`} stopColor="#FBBC04" />
                <stop offset={`${fill * 100}%`} stopColor="#c9c4ba" />
              </linearGradient>
            </defs>
            <path
              fill={`url(#${id})`}
              d="M12 2.5l2.95 6.2 6.8.8-5.03 4.66 1.33 6.72L12 17.52 5.95 20.88l1.33-6.72L2.25 9.5l6.8-.8L12 2.5z"
            />
          </svg>
        );
      })}
    </div>
  );
}

